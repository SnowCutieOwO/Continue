      class="color-block"
      :style="blockStyle"
      @click="handleCopy"
      :title="`点击复制 ${displayColor}`"
      role="button"
      tabindex="0"
      @keydown.enter="handleCopy"
    />
    <!-- 颜色值文本 -->
    <span class="color-text">{{ displayText }}</span>
  </span>
